"""The attention-share bar that stands beside each policy's maps in Figure 4.

Each bar is that policy's action attention split among text, image and action keys, mean over the 100 captured
frames, drawn over exactly the height of the two image rows.  Light fills with the base colour as the edge, the
treatment the boxes of Figures 1 and 2 use.  Every segment carries its percentage, so a segment shorter than the
text is drawn at MIN_H and the others give up the difference in proportion: the printed numbers stay exact while
the smallest band stays readable.  A policy whose split is not captured yet gets an empty outlined bar.
Usage: python make_share_col.py group_shares.json out.tex
"""
import sys, json, math
S = json.load(open(sys.argv[1])); OUTF = sys.argv[2]
BARS = [('native', 4.166), ('yak', 6.564), ('dinol', 11.120), ('qwen', 13.518)]   # left edge of each bar
B, Y0, H, MIN_H = 0.32, 0.02, 3.656, 0.34    # width, baseline, height of the two image rows, smallest legible band
COL = (('text', 'worange'), ('image', 'wblue'), ('action', 'wgreen'))
L = ["  % share of the action expert's attention on text | image | action keys, mean over 100 frames, one bar",
     "  % beside each policy; generated by make_share_col.py (backends/multimodal/scripts/attn_vis) from group_shares.json"]
for key, x in BARS:
    m = S[key]['mean'][:3]; y = Y0
    if any(math.isnan(v) for v in m):
        L.append("  \\draw[wmuted,line width=0.3pt] (%.3f,%.3f) rectangle (%.3f,%.3f);" % (x, Y0, x + B, Y0 + H))
        continue
    h = [H * v for v in m]
    small = [i for i, v in enumerate(h) if v < MIN_H]
    if small:                                    # lift the short bands, take it back from the others in proportion
        owed = sum(MIN_H - h[i] for i in small); rest = sum(h[i] for i in range(3) if i not in small)
        for i in small: h[i] = MIN_H
        for i in range(3):
            if i not in small: h[i] -= owed * h[i] / rest
        print('  %-7s band(s) %s drawn at %.2f cm for legibility' % (key, [COL[i][0] for i in small], MIN_H))
    for (_, c), v, hi in zip(COL, m, h):
        L.append("  \\filldraw[fill=%s,draw=white,line width=0.4pt] (%.3f,%.3f) rectangle (%.3f,%.3f);" % (c, x, y, x + B, y + hi))
        L.append("  \\node[font=\\tiny\\bfseries,text=white,inner sep=0pt] at (%.3f,%.3f) {%d};" % (x + B / 2, y + hi / 2, round(100 * v)))
        y += hi
open(OUTF, 'w').write('\n'.join(L) + '\n'); print('wrote', OUTF, len(L), 'lines')
